/* ------------------------------------------------------------------
   IPTV WEB — site behaviour
   Language switching, the FAQ accordion and the WhatsApp links.
   Translations are in the block above, keyed by the English wording,
   so editing a page never breaks them.
   To change a WhatsApp number or message, use whatsapp-config.js.
------------------------------------------------------------------ */
(function () {
  "use strict";

  var LANGS = ["en", "de", "fr", "es", "it"];
  var page = (document.body.getAttribute("data-page") || "index");
  var I18N = window.I18N || { DICT: {}, META: {} };
  var dict = I18N.DICT[page] || {};
  var meta = I18N.META[page] || {};
  var lang = "en";
  var nodes = null;
  var english = null;

  function collect() {
    if (nodes) return;
    nodes = [];
    english = [];
    var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null, false);
    var n;
    while ((n = walker.nextNode())) {
      if (!n.nodeValue.trim()) continue;
      if (n.parentNode && n.parentNode.nodeName === "SCRIPT") continue;
      nodes.push(n);
      english.push(n.nodeValue);
    }
  }

  /* Turn a phrase into a comparison key: decode any HTML entities and
     collapse runs of whitespace, so "Movies &amp; Series", "Movies & Series"
     and "Movies  &  Series" all match the same dictionary entry. */
  var decoder = document.createElement("textarea");
  function key(s) {
    var t = String(s).trim();
    if (t.indexOf("&") >= 0) {
      decoder.innerHTML = t;
      t = decoder.value;
    }
    return t.replace(/\s+/g, " ");
  }

  /* Build a lookup for each language whose keys are normalised the same
     way, so the dictionary matches the page no matter how either was
     written. Done once, then reused. */
  var lookups = {};
  function lookupFor(target) {
    if (lookups[target]) return lookups[target];
    var src = dict[target] || {};
    var out = {};
    for (var k in src) {
      if (Object.prototype.hasOwnProperty.call(src, k)) out[key(k)] = src[k];
    }
    lookups[target] = out;
    return out;
  }

  function apply(target) {
    if (LANGS.indexOf(target) < 0) target = "en";
    collect();
    var map = lookupFor(target);
    for (var i = 0; i < nodes.length; i++) {
      var src = english[i];
      var translated = map[key(src)];
      nodes[i].nodeValue = (target === "en" || translated === undefined)
        ? src
        : src.replace(src.trim(), translated);
    }
    lang = target;
    document.documentElement.setAttribute("lang", target);

    if (meta[target]) {
      document.title = meta[target].title;
      var d = document.querySelector('meta[name="description"]');
      if (d) d.setAttribute("content", meta[target].desc);
    }

    var btns = document.querySelectorAll("[data-setlang]");
    for (var j = 0; j < btns.length; j++) {
      var on = btns[j].getAttribute("data-setlang") === target;
      btns[j].style.background = on ? "#10b981" : "transparent";
      btns[j].style.color = on ? "#06120e" : "#9a9a9a";
      btns[j].setAttribute("aria-current", on ? "true" : "false");
    }
    wireWhatsApp();
  }

  /* ---------- WhatsApp links (number lives in whatsapp-config.js) ---------- */
  function wireWhatsApp() {
    if (typeof window.waLink !== "function") return false;
    var links = document.querySelectorAll("[data-wa]");
    for (var i = 0; i < links.length; i++) {
      var el = links[i], kind = el.getAttribute("data-wa"), vars = null;
      if (kind === "plan") {
        // send the plan name in the visitor's own language
        var planName = el.getAttribute("data-wa-plan") || "";
        var planMap = lookupFor(lang);
        vars = {
          plan: planMap[key(planName)] || planName,
          price: el.getAttribute("data-wa-price") || ""
        };
      }
      el.setAttribute("href", window.waLink(lang, kind, vars));
      el.setAttribute("target", "_blank");
      el.setAttribute("rel", "noopener");
    }
    return true;
  }

  /* ---------- FAQ accordion ---------- */
  var faq = document.querySelectorAll("[data-faqbtn]");
  for (var f = 0; f < faq.length; f++) {
    (function (btn) {
      var panel = btn.parentNode.querySelector("[data-faqans]");
      if (!panel) return;
      var open = false;
      btn.setAttribute("aria-expanded", "false");
      btn.style.cursor = "pointer";
      btn.addEventListener("click", function () {
        open = !open;
        btn.setAttribute("aria-expanded", open ? "true" : "false");
        panel.style.display = open ? "block" : "none";
      });
    })(faq[f]);
  }
  if (faq[0]) faq[0].click();

  /* ---------- language switcher ---------- */
  document.addEventListener("click", function (e) {
    var b = e.target.closest ? e.target.closest("[data-setlang]") : null;
    if (!b) return;
    e.preventDefault();
    var id = b.getAttribute("data-setlang");
    try { localStorage.setItem("iptvweb_lang", id); } catch (err) {}
    apply(id);
  });

  /* ---------- choose the starting language ---------- */
  var saved = null;
  try { saved = localStorage.getItem("iptvweb_lang"); } catch (err) {}

  if (saved && LANGS.indexOf(saved) >= 0) {
    apply(saved);
  } else {
    var nav = (navigator.language || "en").slice(0, 2).toLowerCase();
    if (LANGS.indexOf(nav) > 0) {
      apply(nav);
    } else {
      apply("en");
      var MAP = { DE:"de", AT:"de", CH:"de", FR:"fr", BE:"fr", ES:"es", MX:"es", AR:"es", IT:"it" };
      fetch("https://ipapi.co/country/")
        .then(function (r) { return r.ok ? r.text() : null; })
        .then(function (c) {
          if (!c) return;
          var l = MAP[String(c).trim().toUpperCase()];
          var already = null;
          try { already = localStorage.getItem("iptvweb_lang"); } catch (err) {}
          if (l && !already) apply(l);
        })
        .catch(function () {});
    }
  }
})();
